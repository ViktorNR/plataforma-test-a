import { chromium } from 'playwright';
const base = process.env.BASE;
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1300, height: 900 } }); const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto(base + '/registro');
await page.fill('input[name=nombre]', 'Color'); await page.fill('input[name=apellido]', 'Prueba');
await page.fill('input[name=email]', `color${Date.now()}@test.cl`); await page.fill('input[name=password]', 'clave-segura-1');
await page.selectOption('select[name=cursoId]', { index: 1 });
await Promise.all([page.waitForURL('**/panel'), page.click('button.btn-primary')]);
await page.goto(base + '/panel/ejercicio/s11-uni-max');
await page.waitForSelector('.sqled');
await page.fill('textarea.sqled-ta', "SELECT nombre, COUNT(*) AS n FROM facultad WHERE id > 3 AND nombre LIKE 'A%' -- hola\nGROUP BY nombre;");
await page.screenshot({ path: '/shots/40-editor-color.png' });
