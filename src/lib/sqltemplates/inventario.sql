CREATE TABLE proveedor (
  id INT PRIMARY KEY,
  nombre VARCHAR(45) NOT NULL,
  personaContacto VARCHAR(45),
  domicilio VARCHAR(45),
  codPostal VARCHAR(5),
  poblacion VARCHAR(45),
  telefono VARCHAR(15),
  fax VARCHAR(15),
  email VARCHAR(45),
  cifnif VARCHAR(12)
);
CREATE TABLE categoria (
  id INT PRIMARY KEY,
  descripcion VARCHAR(45)
);
CREATE TABLE articulo (
  id INT PRIMARY KEY,
  descripcion VARCHAR(80),
  marca VARCHAR(45),
  modelo VARCHAR(45),
  cantidad INT,
  fechaCompra DATE,
  Importe DECIMAL(12,2),
  Proveedor_id INT,
  Categoria_id INT,
  FOREIGN KEY (Proveedor_id) REFERENCES proveedor(id),
  FOREIGN KEY (Categoria_id) REFERENCES categoria(id)
);
CREATE TABLE imagen (
  idArticulo INT PRIMARY KEY,
  imagen MEDIUMBLOB,
  FOREIGN KEY (idArticulo) REFERENCES articulo(id)
);
CREATE TABLE ubicacion (
  id INT PRIMARY KEY,
  ubicacion VARCHAR(45),
  planta VARCHAR(45)
);
CREATE TABLE prestatario (
  id INT PRIMARY KEY,
  nombre VARCHAR(45),
  nif VARCHAR(9),
  domicilio VARCHAR(45),
  codPostal VARCHAR(5),
  poblacion VARCHAR(45),
  telefono VARCHAR(15),
  email VARCHAR(45)
);
CREATE TABLE elemento (
  id INT,
  Ubicacion_id INT,
  Articulo_id INT,
  numSerie VARCHAR(45),
  cantidad INT,
  baja BOOLEAN,
  fechaBaja DATE,
  motivoBaja VARCHAR(200),
  Prestatario_id INT,
  PRIMARY KEY (id, Ubicacion_id, Articulo_id),
  FOREIGN KEY (Ubicacion_id) REFERENCES ubicacion(id),
  FOREIGN KEY (Articulo_id) REFERENCES articulo(id),
  FOREIGN KEY (Prestatario_id) REFERENCES prestatario(id)
);
