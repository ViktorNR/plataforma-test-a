CREATE TABLE ALUMNO
(
RUT_ALUMNO VARCHAR(12) PRIMARY KEY,
NOMBRE VARCHAR(30)
);

CREATE TABLE ASIGNATURA
(
NRC INT PRIMARY KEY,
NOMBRE VARCHAR(12)
);

CREATE TABLE PROFESOR 
(
RUT_PROFESOR VARCHAR(12) PRIMARY KEY,
NOMBRE VARCHAR(30)
);


CREATE TABLE SECCIONES
(
RUT_PROFESOR VARCHAR(12),
RUT_ALUMNO VARCHAR(12),
NRC INT,
NOTAS FLOAT,
PRIMARY KEY (RUT_PROFESOR, RUT_ALUMNO, NRC),
FOREIGN KEY (RUT_PROFESOR) REFERENCES PROFESOR(RUT_PROFESOR),
FOREIGN KEY (RUT_ALUMNO) REFERENCES ALUMNO(RUT_ALUMNO),
FOREIGN KEY (NRC) REFERENCES ASIGNATURA(NRC)
);

